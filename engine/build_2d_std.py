def freeze_hold_seq(frame_file, dur):
    """The freeze hold: the snap frame with a decaying impact shake (<=1s)."""
    f = Image.open(os.path.join(FRAMES, frame_file)).convert("RGB")
    outdir = os.path.join(ANIM, "freeze_hold"); os.makedirs(outdir, exist_ok=True)
    big = f.resize((1116, 1984), Image.LANCZOS)  # margin so the shake never shows an edge
    shakes = [(9, -6), (-7, 5), (4, -3), (-2, 1)]
    for i in range(int(round(dur * FPS)) + 2):
        ox, oy = shakes[i] if i < len(shakes) else (0, 0)
        big.crop((18 + ox, 32 + oy, 18 + ox + W, 32 + oy + H)).save(os.path.join(outdir, f"{i:03d}.png"))
    return outdir


