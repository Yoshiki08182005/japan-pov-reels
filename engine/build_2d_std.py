"""Assemble a standard-format 2D episode (the approved ep02 v4 format),
driven entirely by episodes/<ep>.spec.json — no episode-specific code.

This is build_2d_v4.py generalized. ep02 stays reproducible through
build_2d_v4.py itself; every NEW episode uses this builder.

  python build_2d_std.py epNN_<slug>

Needs (all under episodes/):
  <ep>.spec.json     timeline / overlays / narration placement / sfx / cards /
                     end card / art texts / PDCA metadata (see PIPELINE.md)
  <ep>_frames/*.jpg  AI-generated stills (flat 2D, fixed style block)
  <ep>_clips/*.mp4   image-to-video clips for the living beats (704x1248, 24fps)
  <ep>.script.json + <ep>.voice.json + <ep>_voice/       EN narration (voice.py)
  <ep>_jp.script.json + <ep>_jp.voice.json + <ep>_jp_voice/  JP staff line(s)
Outputs: out/<ep>/final.mp4, cover.jpg, sheet.jpg, meta.json

Format guarantees enforced here (FORMAT.md hard rules):
  - total length clamped to 38-44s
  - EVERY scene segment is a real image-to-video clip (animation guard
    below; a segment defined from a still — including punch-zoom / zoompan
    over a still and the old freeze_hold still — fails the build, naming
    the segment). Only the programmatic cards + end card are non-clips.
  - narration through the WHOLE episode, karaoke subs for every line
  - JP shout kept clean (placement constraints are asserted, build fails loud)
  - cards + end card are animated programmatically (never static >1s)
The motion audit (motion_audit.py) is run as a separate gate after the build.
"""
