# ---------------------------------------------------------------- animation guard
# HARD RULE (user, 2026-11-16; FORMAT.md "Animation" section): EVERY scene
# segment must be a real image-to-video clip, from second 0. A scene beat
# defined from a still image — a plain still, a punch-zoom / zoompan over a
# still, or the old freeze_hold still — is forbidden as that beat's motion;
# camera moves are allowed only on top of animated clips. The freeze gag is
# a <=~0.5s character snap INSIDE a moving clip (declared via "snap_off" on
# the freeze segment), never a held still. The only non-clip material in an
# episode is the programmatic graphic cards (LED recap + stamp end card),
# which are generated by this builder and never appear in SPEC["segments"].
# The motion audit alone does NOT prove compliance (it has passed zoomed
# stills), so the build refuses non-clip scene segments up front, by name.
VIDEO_EXTS = {".mp4", ".mov", ".webm", ".mkv"}
_bad = []
for _s in SPEC.get("segments", []):
    _name = _s.get("name", "<unnamed>")
    if _s.get("kind") != "clip":
        _bad.append(f"segment '{_name}': kind={_s.get('kind')!r} is not 'clip' — scene beats must be "
                    f"real image-to-video clips; stills, freeze_hold and punch-zoom/zoompan over a "
                    f"still are forbidden (FORMAT.md animation rule, 2026-11-16)")
        continue
    _f = _s.get("file")
    if not _f:
        _bad.append(f"segment '{_name}': clip segment has no 'file'")
    elif os.path.splitext(str(_f))[1].lower() not in VIDEO_EXTS:
        _bad.append(f"segment '{_name}': file {_f!r} is not a video clip (expected one of {sorted(VIDEO_EXTS)})")
    elif not os.path.isfile(os.path.join(CLIPD, _f)):
        _bad.append(f"segment '{_name}': clip file not found: episodes/{EP}_clips/{_f}")
if _bad:
    print("ANIMATION GUARD FAILED — every scene beat must be a real animated clip:")
    for _b in _bad:
        print("  -", _b)
    sys.exit(1)

