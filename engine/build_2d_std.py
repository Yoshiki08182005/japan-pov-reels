def dish_layer(t):
    """Small served dish with animated steam curls (phase moves with t)."""
    lay = Image.new("RGBA", (520, 430), (0, 0, 0, 0))
    d = ImageDraw.Draw(lay)
    cx, cy = 260, 300
    for k in range(3):  # steam: sine curls drifting upward, phase from t
        sx = cx - 70 + k * 70
        pts = []
        for j in range(26):
            u = j / 25.0
            pts.append((sx + 16 * math.sin(2 * math.pi * (u * 1.2 - t / 0.9) + k), cy - 90 - u * 130))
        d.line(pts, fill=ORANGE + (255,), width=9, joint="curve")
    d.ellipse((cx - 190, cy - 42, cx + 190, cy + 66), outline=ORANGE, width=10)  # plate
    d.ellipse((cx - 140, cy - 30, cx + 140, cy + 30), outline=ORANGE, width=6)
    for dx, dy, r in [(-70, -52, 34), (0, -66, 40), (72, -50, 32), (-30, -40, 28), (40, -38, 26)]:  # food mound
        d.ellipse((cx + dx - r, cy + dy - r, cx + dx + r, cy + dy + r), outline=ORANGE, width=7)
    d.line((cx + 120, cy - 120, cx + 210, cy + 6), fill=ORANGE, width=9)  # chopsticks
    d.line((cx + 148, cy - 128, cx + 226, cy - 14), fill=ORANGE, width=9)
    return lay


def coin_layer(t, big_text):
    """A yen coin that keeps flipping (x-scale oscillation, period 0.9s)."""
    lay = Image.new("RGBA", (380, 380), (0, 0, 0, 0))
    d = ImageDraw.Draw(lay)
    sx = 0.3 + 0.7 * abs(math.cos(math.pi * t / 0.9))
    rx = 168 * sx
    d.ellipse((190 - rx, 22, 190 + rx, 358), outline=ORANGE, width=11)
    d.ellipse((190 - rx * 0.78, 62, 190 + rx * 0.78, 318), outline=ORANGE, width=5)
    if sx > 0.55:  # text only while the face is readable
        d.text((190, 150), "¥", font=A.font(110), fill=ORANGE, anchor="mm")
        d.text((190, 248), big_text.replace("¥", ""), font=A.fit(big_text, 200, 64), fill=ORANGE, anchor="mm")
    return lay


def card_seq(idx, cfg, dur):
    outdir = os.path.join(ANIM, f"card{idx}"); os.makedirs(outdir, exist_ok=True)
    base = card_base(cfg["title"])
    icon = cfg.get("icon", "machine")
    ticket = ticket_layer(cfg.get("icon_label", ""), cfg.get("icon_text", "")) if icon == "ticket" else None
    head = owner_head_layer() if icon == "owner" else None
    sign = sign_layer(cfg.get("sign_text", "ORDER HERE")) if icon == "owner" else None
    n = int(round(dur * FPS)) + 2
    for i in range(n):
        t = i / FPS
        fr = base.copy(); d = ImageDraw.Draw(fr)
        if icon == "machine":
            draw_machine_icon(d, int(t / 0.33) % 9)  # buttons light up in sequence
        elif icon == "ticket":
            if t < 0.45:
                u = t / 0.45; e = 1 - (1 - u) ** 3
                xoff, rot, sc = -580 * (1 - e), -10 * (1 - e), 1.0
            else:
                xoff, rot, sc = 0.0, 0.0, 1 + 0.05 * math.sin(2 * math.pi * (t - 0.45) / 0.8)
            lay = ticket.rotate(rot, resample=Image.BICUBIC, expand=True) if rot else ticket
            if sc != 1.0:
                lay = lay.resize((int(lay.width * sc), int(lay.height * sc)), Image.BICUBIC)
            fr.alpha_composite(lay, (int(540 + xoff - lay.width / 2), int(515 - lay.height / 2)))
        elif icon == "owner":
            bob = round(7 * math.sin(2 * math.pi * t / 0.9))
            fr.alpha_composite(head, (540 - 170, 400 + bob))
            sg = sign.rotate(7 * math.sin(2 * math.pi * t / 1.15), resample=Image.BICUBIC, expand=True)
            fr.alpha_composite(sg, (int(540 - sg.width / 2), int(774 + bob - sg.height / 2)))
        elif icon == "dish":
            lay = dish_layer(t)
            fr.alpha_composite(lay, (540 - lay.width // 2, 330))
        elif icon == "coin":
            lay = coin_layer(t, cfg.get("icon_text", ""))
            fr.alpha_composite(lay, (540 - lay.width // 2, 360))
        draw_progress(d, t, dur)
        fr.convert("RGB").save(os.path.join(outdir, f"{i:03d}.png"))
    return outdir


