def endcard_seq(dur):
    outdir = os.path.join(ANIM, "endcard"); os.makedirs(outdir, exist_ok=True)
    S, R, F = endcard_static(), ring_layer(), follow_layer()
    n = int(round(dur * FPS)) + 2
    for i in range(n):
        t = i / FPS
        u = min(1.0, t / 0.30)
        s = 1 + 1.5 * (1 - u) ** 3
        rot = -6 - 10 * (1 - u)
        stamp = S.copy()
        stamp.alpha_composite(R.rotate(-14.0 * t, resample=Image.BICUBIC, center=(EC_CX, EC_CY)))
        if rot:
            stamp = stamp.rotate(rot, resample=Image.BICUBIC, center=(EC_CX, EC_CY))
        if s != 1.0:
            big = stamp.resize((int(W * s), int(H * s)), Image.BICUBIC)
            canvas = Image.new("RGBA", (W, H), (0, 0, 0, 0))
            canvas.alpha_composite(big, (int(EC_CX - EC_CX * s), int(EC_CY - EC_CY * s)))
            stamp = canvas
        frame = Image.new("RGBA", (W, H), (5, 5, 5, 255))
        frame.alpha_composite(stamp)
        if t > 0.35:
            sc = 1 + 0.07 * math.sin(2 * math.pi * (t - 0.35) / 0.85)
            fw, fh = int(F.width * sc), int(F.height * sc)
            frame.alpha_composite(F.resize((fw, fh), Image.BICUBIC), (540 - fw // 2, 1330 - fh // 2))
        frame.convert("RGB").save(os.path.join(outdir, f"{i:03d}.png"))
    return outdir


# ---------------------------------------------------------------- timeline from spec
# Segment kinds: clip {file,in} / still {frame|crop, zoom:[z0,z1]} /
# freeze_hold {from} / card {card} / endcard {}
# NOTE: the animation guard above rejects every non-"clip" scene segment, so
# the still / freeze_hold branches below are unreachable for scene segments —
# they remain only so an unexpected kind fails loudly instead of silently.
RAW_SEGS = []
for s in SPEC["segments"]:
    RAW_SEGS.append((s["name"], s["kind"], s, float(s["dur"])))
card_cfgs = SPEC["cards"]
card_durs = {}
for c in card_cfgs:
    card_durs[c["line"]] = max(3.0, N[c["line"]] + 0.55)
end_line = ECFG["line_id"]
end_dur = max(3.4, N[end_line] + 1.1)
story_end = sum(d for _n, _k, _s, d in RAW_SEGS)
total = story_end + sum(card_durs.values()) + end_dur
if total > 44.0:  # clamp: shave card padding first
    over = total - 43.6
    for c in card_cfgs:
        lid = c["line"]
        cut = min(over, card_durs[lid] - (N[lid] + 0.28))
        if cut > 0:
            card_durs[lid] -= cut; over -= cut
    if over > 0:
        end_dur = max(N[end_line] + 0.5, end_dur - over)
    total = story_end + sum(card_durs.values()) + end_dur
if total < 38.0:
    end_dur += 38.0 - total; total = 38.0

SEGS = []  # (name, kind, src, dur, zoom) — src resolved per kind
for name, kind, s, dur in RAW_SEGS:
    if kind == "clip":
        SEGS.append((name, "clip", (s["file"], float(s.get("in", 0.0))), dur, None))
    elif kind == "still":
        src = CROPS[s["crop"]] if "crop" in s else os.path.join(FRAMES, s["frame"])
        SEGS.append((name, "still", src, dur, tuple(s["zoom"]) if "zoom" in s else None))
    elif kind == "freeze_hold":
        SEGS.append((name, "seq", freeze_hold_seq(s["from"], dur), dur, None))
    else:
        raise SystemExit(f"unknown segment kind {kind}")
for i, c in enumerate(card_cfgs, 1):
    SEGS.append((f"card{i}", "seq", card_seq(i, c, card_durs[c["line"]]), card_durs[c["line"]], None))
SEGS.append(("endcard", "seq", endcard_seq(end_dur), end_dur, None))
STARTS = {}
_t = 0.0
for name, _k, _s, dur, _z in SEGS:
    STARTS[name] = _t; _t += dur
TOTAL = _t
# The freeze snap now lives INSIDE a clip segment (animation rule 2026-11-16):
# declared as "snap_off" (offset within that clip) or spec-level
# "freeze_snap": {"seg": <name>, "off": <seconds>}. Informational only
# (meta + summary print); SFX placement comes from the spec's sfx cues.
SNAP_T = None
for s in SPEC["segments"]:
    if "snap_off" in s:
        SNAP_T = STARTS[s["name"]] + float(s["snap_off"])
        break
if SNAP_T is None and isinstance(SPEC.get("freeze_snap"), dict):
    _fs = SPEC["freeze_snap"]
    SNAP_T = STARTS[_fs["seg"]] + float(_fs.get("off", 0.0))
SHOUT_CFG = SPEC["shout"]
SHOUT_T = STARTS[SHOUT_CFG["seg"]] + float(SHOUT_CFG["off"])
print(f"total {TOTAL:.2f}s  story {story_end:.1f}s  cards " +
      " ".join(f"{k}={v:.2f}" for k, v in card_durs.items()) + f" end={end_dur:.2f}  snap@{(f'{SNAP_T:.2f}' if SNAP_T is not None else 'n/a')} shout@{SHOUT_T:.2f}")

# ---------------------------------------------------------------- narration placement
def _place(chain, gap=0.15):
    out, prev_end = {}, None
    for lid, seg, off in chain:
        earliest = STARTS[seg] + float(off)
        st = earliest if prev_end is None else max(earliest, prev_end + gap)
        out[lid] = st
        prev_end = st + N[lid]
    return out


NARR = {}
for chain in SPEC["narration"].get("chains", []):
    NARR.update(_place(chain))
for lid, seg, off in SPEC["narration"].get("singles", []):
    NARR[lid] = STARTS[seg] + float(off)
for con in SPEC["narration"].get("constraints", []):
    lid = con["line"]
    limit = STARTS[con["end_before"]["seg"]] + float(con["end_before"].get("off", 0.0)) - float(con.get("margin", 0.1))
    end = NARR[lid] + N[lid]
    assert end <= limit, f"{lid} overruns: ends {end:.2f} > limit {limit:.2f} — shorten the line in {EP}.script.json"
print("narration:", {k: (round(v, 2), round(v + N[k], 2)) for k, v in NARR.items()})


# ---------------------------------------------------------------- overlays (stamps / pills / bubble)
def stamp_seq(stamp_png, outdir, dur, cx, cy, final_w):
    os.makedirs(outdir, exist_ok=True)
    st = Image.open(stamp_png).convert("RGBA")
    n = int(round(dur * FPS))
    for i in range(n):
        u = min(1.0, (i / FPS) / 0.22)
        s = 1 + 2 * (1 - u) ** 3
        w = int(final_w * s); h = int(st.height * w / st.width)
        frame = Image.new("RGBA", (W, H), (0, 0, 0, 0))
        frame.alpha_composite(st.resize((w, h)), (int(cx - w / 2), int(cy - h / 2)))
        frame.save(os.path.join(outdir, f"{i:03d}.png"))
    return outdir


def pop_seq(png, outdir, dur, cx, cy, s0=1.35, back=False):
    os.makedirs(outdir, exist_ok=True)
    im = Image.open(png).convert("RGBA")
    n = int(round(dur * FPS))
    for i in range(n):
        t = i / FPS
        if back:
            u = min(1.0, t / 0.2); c1 = 1.70158; c3 = c1 + 1
            s = 0.5 + 0.5 * (1 + c3 * (u - 1) ** 3 + c1 * (u - 1) ** 2) if u < 1 else 1.0
        else:
            u = min(1.0, t / 0.16); s = s0 + (1 - s0) * (1 - (1 - u) ** 3)
        w = int(im.width * s); h = int(im.height * s)
        frame = Image.new("RGBA", (W, H), (0, 0, 0, 0))
        frame.alpha_composite(im.resize((w, h)), (int(cx - w / 2), int(cy - h / 2)))
        frame.save(os.path.join(outdir, f"{i:03d}.png"))
    return outdir


