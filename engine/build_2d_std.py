def ass_time(t):
    h = int(t // 3600); m = int(t % 3600 // 60); s = t % 60
    return f"{h}:{m:02d}:{s:05.2f}"


def word_events():
    lines = [(lid, NARR[lid]) for lid in SPEC["narration"].get("order", list(NARR.keys())) if lid in NARR]
    for i, c in enumerate(card_cfgs, 1):
        lines.append((c["line"], STARTS[f"card{i}"] + 0.12))
    lines.append((end_line, STARTS["endcard"] + 0.12))
    evs = []
    for lid, start in lines:
        info = EN["lines"][lid]
        words = []
        chunks = info["chunks"]
        for ci, ch in enumerate(chunks):
            ctext = ch["text"].replace("[", "").replace("]", "")
            cstart = start + ch["t"]
            cend = start + (chunks[ci + 1]["t"] if ci + 1 < len(chunks) else info["dur"])
            ws = ctext.split()
            lens = [max(1, len(w)) for w in ws]; tot = sum(lens); acc = 0.0
            for w in ws:
                wlen = max(1, len(w))
                words.append([cstart + (cend - cstart) * acc / tot, cstart + (cend - cstart) * (acc + wlen) / tot, w])
                acc += wlen
        texts = [w[2] for w in words]
        brk = None
        if sum(len(x) for x in texts) > 34:
            best, acc = 10 ** 9, 0
            for i in range(1, len(texts)):
                a = len(" ".join(texts[:i])); b = len(" ".join(texts[i:]))
                if abs(a - b) < best:
                    best, brk = abs(a - b), i
        for wi, (ws_, we_, _w) in enumerate(words):
            parts = []
            for j, (_s, _e, wtxt) in enumerate(words):
                if j == brk:
                    parts.append("\\N")
                elif j > 0:
                    parts.append(" ")
                col = r"{\c&H2E9DFF&}" if j <= wi else r"{\c&HFFFFFF&}"
                parts.append(col + wtxt.replace("{", "").replace("}", ""))
            evs.append((ws_, max(we_, ws_ + 0.05), "".join(parts)))
    return evs


